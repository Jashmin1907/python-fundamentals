# Arithmetic, comparison, and logical operators
a = 17
b = 5

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Floor division:", a // b)
print("Remainder:", a % b)
print("Power:", a ** b)

print("a == b:", a == b)
print("a != b:", a != b)
print("a < b:", a < b)

age = 20
has_id = True
print("Allowed:", age >= 18 and has_id)
